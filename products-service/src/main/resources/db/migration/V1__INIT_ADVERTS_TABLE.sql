    has_security                 BOOLEAN,
    has_video_security           BOOLEAN,
    has_children_playground      BOOLEAN,
    has_sport_playground         BOOLEAN,
    payment_type                 VARCHAR(50),
    has_documents                BOOLEAN,
    description                  TEXT         NOT NULL,
    work_experience              NUMERIC(10, 2),
    advantages                   TEXT,
    employment                   VARCHAR(50),
    work_format                  VARCHAR(50),
    pet_breed                    VARCHAR(255),
    pet_name                     VARCHAR(255),
    pet_color                    VARCHAR(255),
    transaction_scope            VARCHAR(50),
    is_profitable                BOOLEAN,
    business_form                VARCHAR(50),
    offer_type                   VARCHAR(50),
    pay_back_period              VARCHAR(255),
    address                      VARCHAR(255) NOT NULL,
    contacts                     VARCHAR(255) NOT NULL,
    is_in_elastic                BOOLEAN      NOT NULL DEFAULT FALSE,
    user_id                      VARCHAR(255) NOT NULL,
    created_at                   TIMESTAMP WITHOUT TIME ZONE,
    updated_at                   TIMESTAMP WITHOUT TIME ZONE
