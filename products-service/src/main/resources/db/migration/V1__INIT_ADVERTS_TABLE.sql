    last_name                    VARCHAR(255),
    fathers_name                 VARCHAR(255),
    gender                       VARCHAR(50),
    category                     VARCHAR(255) NOT NULL,
    sub_category                 VARCHAR(255),
    title                        VARCHAR(255) NOT NULL,
    profession                   VARCHAR(255),
    sphere                       VARCHAR(255),
    brand                        VARCHAR(255),
    model                        VARCHAR(255),
    year_of_manufacture          INT,
    color                        VARCHAR(100),
    is_on_the_go                 BOOLEAN,
    vehicle_body_type            VARCHAR(255),
    vehicle_kpp                  VARCHAR(50),
    owners_pts                   INT,
    milage                       BIGINT,
    engine_capacity              INT,
    horse_power                  INT,
    drive                        VARCHAR(50),
    steering_wheel               VARCHAR(50),
    price                        VARCHAR(255) NOT NULL,
    price_for                    VARCHAR(50),
    vessel_type                  VARCHAR(50),
    vessel_length                INT,
    vessel_width                 INT,
    vessel_draft                 INT,
    max_passengers               INT,
    vessel_body_material         VARCHAR(255),
